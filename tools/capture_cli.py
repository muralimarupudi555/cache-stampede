"""Run the tool for real and commit what it printed.

A README that quotes invented output is a README that drifts. This runs the real command
and writes what came back, exit codes included, so the block in
the documentation is a transcript rather than a description.

Regenerated by `make bench` rather than by `make verify`. This repository measures real
threads against a real clock, so the counts move slightly between runs, and a gate that
leaves uncommitted changes behind every time it runs is a gate people stop reading the
output of.
"""

from __future__ import annotations

import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "cli-output.md"

INVOCATIONS = [
    ("A plain TTL cache on one hot key",
     ["--cache", "naive", "--duration-seconds", "3"]),
    ("The same load, with jittered expiry",
     ["--cache", "jittered", "--duration-seconds", "3"]),
    ("The same load, with single flight",
     ["--cache", "single_flight", "--duration-seconds", "3"]),
    ("A scenario that cannot show a stampede",
     ["--origin-seconds", "0"]),
]

PREAMBLE = (
    "Generated by `tools/capture_cli.py`, which runs the real command against a real "
    "load against a real thread pool and records what came back. Regenerated by "
    "`make bench`; only the timings and the exact counts move between runs."
)


def main() -> None:
    sections = ["# Captured output", "", PREAMBLE, ""]
    for title, args in INVOCATIONS:
        result = subprocess.run(
            ["cache-stampede", *args],
            cwd=ROOT, capture_output=True, text=True, check=False,
        )
        body = (result.stdout + result.stderr).rstrip()
        sections += [
            f"## {title}", "",
            "```console",
            f"$ cache-stampede {' '.join(args)}",
            body,
            "$ echo $?", str(result.returncode),
            "```", "",
        ]
        print(f"  captured `{' '.join(args)}` -> exit {result.returncode}")

    OUT.write_text("\n".join(sections))
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
